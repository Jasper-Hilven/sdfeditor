using System.Globalization;
using System.Text;

namespace Kk.Rigging.Skeletons;

/// <summary>Writes a "stick" format 2 model for a skeleton: one capsule per bone from its head to its first child's head.</summary>
public static class SkeletonStick
{
    private static readonly CultureInfo Inv = CultureInfo.InvariantCulture;

    /// <summary>The world rest head of every joint in the format 2 model space (ModelRest is internal to this assembly).</summary>
    public static (double X, double Y, double Z)[] RestHeads(SkeletonFile file) =>
        file.ModelRest().Select(r => (r.Position.X, r.Position.Y, r.Position.Z)).ToArray();

    public static string Write(SkeletonFile file, string material, string? comment = null)
    {
        var joints = file.Joints;
        var rest = file.ModelRest();
        var children = joints.Select(_ => new List<int>()).ToArray();
        foreach (var j in joints.Skip(1)) children[j.Parent].Add(j.Index);

        var text = new StringBuilder();
        text.Append("# ").Append(comment ?? $"Stick model of the {file.Name} skeleton: a capsule per bone, generated by kk skeleton stick.").Append('\n');
        text.Append("format 2\n");
        text.Append("skeleton=").Append(file.Name).Append('\n');
        text.Append("collider bones\n\n");
        text.Append("Material material=").Append(material).Append('\n');

        var level = 1;
        if (children[0].Count > 1)
        {
            text.Append(Indent(level++)).Append("Union\n");
        }
        foreach (var child in children[0]) Emit(child, level);
        return text.ToString();

        void Emit(int index, int depth)
        {
            var head = rest[index].Position;
            D3 tail;
            if (children[index].Count > 0)
                tail = rest[children[index][0]].Position;
            else
            {
                var half = (head - rest[joints[index].Parent].Position) * 0.5;
                if (half.Length < 0.02)
                    half = half.Length > 1e-9 ? half / half.Length * 0.02 : new D3(0, 0.02, 0);
                tail = head + half;
            }
            var radius = Math.Clamp(0.25 * (tail - head).Length, 0.012, 0.06);
            var pad = Indent(depth);
            text.Append(pad).Append($"Bone name={joints[index].Alias} head={V(head)} tail={V(tail)}\n");
            text.Append(pad).Append("    ").Append($"Capsule a={V(head)} b={V(tail)} radius={N(radius)}\n");
            foreach (var child in children[index]) Emit(child, depth + 1);
        }
    }

    private static string Indent(int level) => new(' ', 4 * level);

    private static string V(D3 v) => $"({N(v.X)}, {N(v.Y)}, {N(v.Z)})";

    private static string N(double value)
    {
        var s = value.ToString("0.#####", Inv);
        return s is "-0" ? "0" : s;
    }
}
